import {
  type CodeGenerator,
  type Module,
  type RecordLocation,
  convertCase,
} from "skir-internal";
import { z } from "zod";

const Config = z.strictObject({});

type Config = z.infer<typeof Config>;

class MoonbitCodeGenerator implements CodeGenerator<Config> {
  readonly id = "skir-moonbit-gen";
  readonly configType = Config;

  generateCode(input: CodeGenerator.Input<Config>): CodeGenerator.Output {
    const outputFiles: CodeGenerator.OutputFile[] = [];
    for (const module of input.modules) {
      outputFiles.push({
        path: module.path.replace(/\.skir$/, ".mbt"),
        code: new MoonbitSourceFileGenerator(module).generate(),
      });
    }
    return { files: outputFiles };
  }
}

class MoonbitSourceFileGenerator {
  constructor(private readonly inModule: Module) {}

  generate(): string {
    const out: string[] = [];

    out.push(
      "//  ______                        _               _  _  _\n",
      "//  |  _  \\                      | |             | |(_)| |\n",
      "//  | | | |  ___    _ __    ___  | |_    ___   __| | _ | |_\n",
      "//  | | | | / _ \\  | '_ \\  / _ \\ | __|  / _ \\ / _` || || __|\n",
      "//  | |/ / | (_) | | | | || (_) || |_  |  __/| (_| || || |_ \n",
      "//  |___/   \\___/  |_| |_| \\___/  \\__|  \\___| \\__,_||_| \\__|\n",
      "//\n",
      "// Generated by skir-moonbit-gen\n",
      "// Skeleton implementation: structs and enums only (empty declarations).\n\n",
    );

    for (const record of this.inModule.records) {
      this.writeRecord(record, out);
    }

    return out.join("");
  }

  private writeRecord(record: RecordLocation, out: string[]): void {
    const recordType = record.record.recordType;
    const typeName = this.getTypeName(record);

    out.push(`// ${recordType} ${typeName}\n`);
    if (recordType === "struct") {
      out.push(`struct ${typeName} {}\n\n`);
    } else {
      out.push(`enum ${typeName} {}\n\n`);
    }
  }

  private getTypeName(record: RecordLocation): string {
    const names = record.recordAncestors
      .map((x) => x.name?.text)
      .filter((x): x is string => Boolean(x));
    const segments = (names.length ? names : [record.record.name.text]).map(
      (part) => convertCase(part, "UpperCamel"),
    );
    return segments.join("_");
  }
}

export const GENERATOR = new MoonbitCodeGenerator();
